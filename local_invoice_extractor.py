_MONTH_NUMS = {
    m: i
    for i, m in enumerate(
        ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"],
        start=1,
    )
}

# Digit-adjacent lookarounds instead of \b: PDF text-run extraction often
# loses the whitespace between two visually-adjacent-but-separately-drawn
# text runs (e.g. a label glued straight onto the next cell's text, as in
# "Order Date:\xa018/09/2018Dell Order No:") — \b fails to match at a
# digit/letter boundary because both are "word" characters to \b, so
# "2018Dell" would silently never match at all. (?<!\d)/(?!\d) only guard
# against the date being a substring of a *longer number*, which is the
# actual failure mode worth preventing.
_DATE_PATTERNS = [
    (re.compile(r"(?<!\d)(\d{1,2})/(\d{1,2})/(\d{4})(?!\d)"), "dmy4"),
    (re.compile(r"(?<!\d)(\d{4})-(\d{2})-(\d{2})(?!\d)"), "iso"),
    # [,\s-]+ (not a single [-\s] char) so "30 November, 2025" — comma
    # *and* space between month and year — matches too, not just the
    # hyphen/space-only "04-Apr-2024" style.
    (re.compile(r"(?<!\d)(\d{1,2})[-\s]([A-Za-z]{3,9})[,\s-]+(\d{4})(?!\d)"), "dmonY"),
    # US-style "Mon Mar 03 2025" (month name *before* the day) — the
    # leading weekday-name word is optional and not captured.
    (
        re.compile(
            r"(?:\b[A-Za-z]{3,9}\s+)?\b([A-Za-z]{3,9})\s+(\d{1,2})\s*,?\s+(\d{4})(?!\d)"
        ),
        "monDY",
    ),
    # Ordinal "5th May 2026" / "21st December 2024". The (?<!\d) guard is
    # load-bearing, not decorative: a run-together "Tax Invoice # 47815th
    # May 2026" (invoice number glued directly onto the date with no
    # separator — a real case seen on a NextGen Living-style invoice)
    # would otherwise let \d{1,2} backtrack into the invoice number and
    # misread "15th" out of "...4781" + "5th", silently returning the
    # wrong day. Refusing to match when the leading digit is
    # digit-adjacent means this glued case is correctly left unparsed
    # (falls through to "no date found") rather than parsed wrong.
    (
        re.compile(
            r"(?<!\d)(\d{1,2})(?:st|nd|rd|th)\s+([A-Za-z]{3,9})\s+(\d{4})(?!\d)",
            re.IGNORECASE,
        ),
        "ordDMY",
    ),
    (re.compile(r"(?<!\d)(\d{1,2})/(\d{1,2})/(\d{2})(?!\d)"), "dmy2"),
]

_DATE_CONTEXT_KEYWORDS = (
    "invoice date", "order date", "purchase date", "date issued", "date:",
    "placed on",
)

# Bounded to 1-2 digits, AND required not to be preceded by another digit
# or hyphen, deliberately: PDF text extraction sometimes runs an adjacent
# table cell's digits (an item/SKU code) straight into the next cell's
# text with no space, e.g. "344-62421" + "1Yr Ltd Hardware Warranty" ->
# "344-624211Yr...". An unbounded \d+ would swallow the SKU's digits too
# and produce nonsense (this previously crashed date math on a
# multi-hundred-thousand-year result); even bounded to 2 digits it would
# still misread "...62421" + "1Yr" as "11Yr". The (?<![\d\-]) lookbehind
# rejects exactly that glued case — if only a glued match exists, we fall
# through to the honest "not found, defaulted to 1 year" path instead of
# trusting a number that's provably contaminated by an adjacent code.
_WARRANTY_DURATION_RE = re.compile(
    r"(?<![\d\-])(\d{1,2})\s*[- ]?\s*(?:yr|year|years)\b", re.IGNORECASE
)

KNOWN_BRANDS = [
    "Daisy Pool Covers", "Apple", "Samsung", "Dell", "HP", "Lenovo", "Asus",
    "Acer", "LG", "Sony", "Panasonic", "Whirlpool", "Bosch", "Garmin",
    "Fitbit", "Google", "Microsoft", "Electrolux", "Fisher & Paykel",
    "Breville", "KitchenAid", "Toshiba", "Hisense", "TCL", "JBL", "Bose",
    "Nikon", "Canon", "GoPro", "Dyson", "Philips", "Sharp", "Haier",
    "Maytronics", "Omron",
]

# Column-header words that can end up looking like a valid "product name"
# or "code" candidate purely because of where they land in the extracted
# text — used by both the code-pair and Description-header search paths
# below to reject header/label text rather than trust it as data.
_TABLE_HEADER_WORDS = {
    "item", "sku", "qty", "qty.", "quantity", "subtotal", "sub-total",
    "sub total", "description", "product description", "unit price",
    "price", "total price", "total", "amount", "value", "disc%",
    "discount", "disc", "gst", "tax", "delivered to", "delivered",
    "billing", "shipping",
}

CATEGORY_KEYWORDS = [
    ("Electronics", ["iphone", "smartphone", "phone", "laptop", "computer", "television",
                      " tv ", "camera", "smartwatch", "tablet", "monitor", "headphone"]),
    ("Appliances", ["refrigerator", "fridge", "washing machine", "dishwasher",
                     "microwave", "oven", "vacuum", "air conditioner"]),
    ("Pool Equipment", ["pool cover", "pool roller", "pool pump", "pool cleaner"]),
    ("Furniture", ["sofa", "wardrobe", "mattress", "recliner"]),
]

_BOILERPLATE_STARTS = (
    "tax invoice", "invoice", "receipt", "thank you", "phone", "abn",
    "www.", "http", "order confirmation", "customer",
)


def _clean_str(value):
    if value is None:
        return None
    value = re.sub(r"\s+", " ", str(value)).strip()
    return value or None


def _parse_date_match(m, kind, warnings):
    try:
        if kind == "dmy4":
            d, mo, y = m.groups()
            return datetime.date(int(y), int(mo), int(d))
        if kind == "dmy2":
            d, mo, y = m.groups()
            yy = int(y)
            year = 2000 + yy if yy < 70 else 1900 + yy
            return datetime.date(year, int(mo), int(d))
        if kind == "dmonY":
            d, mon, y = m.groups()
            month = _MONTH_NUMS.get(mon.lower()[:3])
            if not month:
                return None
            return datetime.date(int(y), month, int(d))
        if kind in ("monDY", "ordDMY"):
            if kind == "monDY":
                mon, d, y = m.groups()
            else:
                d, mon, y = m.groups()
            month = _MONTH_NUMS.get(mon.lower()[:3])
            if not month:
                return None
            return datetime.date(int(y), month, int(d))
        if kind == "iso":
            y, mo, d = m.groups()
            return datetime.date(int(y), int(mo), int(d))
    except ValueError:
        return None
    return None


def _find_purchase_date(text, warnings):
    candidates = []
    for regex, kind in _DATE_PATTERNS:
        for m in regex.finditer(text):
            d = _parse_date_match(m, kind, warnings)
            if d is None:
                continue
            context = text[max(0, m.start() - 40) : m.start()].lower()
            priority = 2 if any(kw in context for kw in _DATE_CONTEXT_KEYWORDS) else (1 if "date" in context else 0)
            candidates.append((priority, m.start(), d))
    if not candidates:
        warnings.append("purchase_date: no date-like value found in the document text.")
        return None
    candidates.sort(key=lambda c: (-c[0], c[1]))
    best = candidates[0]
    if best[0] == 0:
        warnings.append(
            "purchase_date: no 'date' label found near the chosen value; used "
            "the first date-like value in the document — please verify."
        )
    return best[2].isoformat()


def _find_brand(text, warnings):
    for brand in KNOWN_BRANDS:
        if re.search(re.escape(brand), text, re.IGNORECASE):
            return brand
    warnings.append(
        "other_brand_name: not matched against the known-brand list "
        "(local_invoice_extractor.KNOWN_BRANDS) — add it there if this "
        "brand should be recognized."
    )
    return None


def _find_product_code_pair(text):
    """Tabular invoices often print a SKU code on its own line immediately
    followed by a line starting with that same code plus the full
    description, e.g. '525TB' then '525TB Titanium Blue Pool Cover'. This
    catches both the product name AND the code in one reliable shot —
    tried before the weaker single-field heuristics below.

    The code candidate must contain a digit: real SKUs almost always do,
    plain English words practically never do, and requiring one is what
    stops this from misfiring on an unrelated pair of adjacent section
    headers like "Shipping" followed by "Shipping Method" — which has
    exactly the same "line, then a line starting with that line" shape
    this function looks for, but is not product data at all."""
    lines_list = [ln.strip() for ln in text.split("\n")]
    for i in range(len(lines_list) - 1):
        code, nxt = lines_list[i], lines_list[i + 1]
        if not (2 <= len(code) <= 15):
            continue
        if not re.match(r"^[A-Za-z0-9][A-Za-z0-9\-]*$", code):
            continue
        if not re.search(r"\d", code):
            continue
        if nxt.startswith(code) and len(nxt) > len(code) + 2:
            description = nxt[len(code) :].strip(" -:")
            if description and not description[0].isdigit():
                return _clean_str(description), code
    return None, None


def _find_description_then_code(text):
    """The reverse convention from _find_product_code_pair: some invoices
    print the description FIRST and a short SKU-like code on the line
    right after it (e.g. 'Dolphin M 700' then '99996710-AU'), rather than
    the code-then-matching-prefix pattern above.

    This is the weakest/most heuristic of the product-name strategies —
    tried only after the asterisk-line and code-pair checks have both
    failed (see the priority order in extract_fields) — because unlike
    those two, it has no exact-match anchor tying the two lines together;
    it's just "some text, then some code-shaped text on the next line".
    The one thing that reliably distinguishes a real SKU from adjacent
    unrelated data (an email followed by a phone number, a street number
    followed by a suburb, a masked card number, a terminal ID) is that
    real SKUs mix LETTERS and DIGITS — a pure-digit line (a phone number,
    an account number) or a pure-letter line never is one. Checked AFTER
    merging a wrapped trailing segment, since a SKU's first fragment can
    itself be all-digit before the merge (e.g. '99996710-' + 'AU')."""
    lines_list = [ln.strip() for ln in text.split("\n")]
    for i in range(len(lines_list) - 1):
        desc, code = lines_list[i], lines_list[i + 1]
        if not (5 <= len(desc) <= 90):
            continue
        if desc.lower() in _TABLE_HEADER_WORDS:
            continue
        if not re.search(r"[A-Za-z]", desc):
            continue
        # A trailing hyphen is the tell that THIS line is itself a
        # fragment of a wrapped multi-line code, not a real description —
        # a long SKU (e.g. '100-PERCENT-BATTERY-HEALTH-IPHONE-13-PRO')
        # word-wrapped across several short lines produces a run of
        # hyphen-ending fragments, and without this guard the loop pairs
        # two ADJACENT FRAGMENTS OF THE SAME CODE as if one were the
        # description and the next were its code.
        if desc.endswith("-"):
            continue
        # A real item title conventionally starts with a capital letter or
        # digit (or a brand-style lowercase-then-capital lead-in, like
        # "iPhone"). A line starting with an ordinary lowercase word is
        # very likely the tail end of a wrapped sentence/note from the
        # line above it — e.g. "(Note: this / option delays dispatch by
        # one business day)" — not a genuine product name, even though it
        # otherwise looks like harmless descriptive text.
        if not re.match(r"^(?:[A-Z0-9]|[a-z][A-Z])", desc):
            continue
        if not re.match(r"^[A-Za-z0-9][A-Za-z0-9\-]{1,29}$", code):
            continue
        if code.endswith("-") and i + 2 < len(lines_list):
            cont = lines_list[i + 2]
            if re.match(r"^[A-Za-z0-9]{1,8}$", cont):
                code = code + cont
        if not (re.search(r"[A-Za-z]", code) and re.search(r"\d", code)):
            continue
        return _clean_str(desc), code
    return None, None


def _find_asterisk_product_name(text):
    """Highest-confidence product-name signal: retail receipts commonly
    mark taxable/purchased line items with a leading '*'. Tried first,
    ahead of every other strategy, because the marker is explicit rather
    than inferred."""
    lines_list = text.split("\n")
    for i, raw_line in enumerate(lines_list):
        m = re.match(r"^\*\s*([A-Za-z0-9][^\n]{2,80})$", raw_line.strip())
        if not m:
            continue
        name = m.group(1)
        # Retail receipts often wrap the product name onto a short
        # continuation line (e.g. 'GRAPHITE CA' after 'GARMIN - VENU 2S
        # SLATE BEZEL') — merge it in if the next line looks like a
        # continuation rather than a new field.
        if i + 1 < len(lines_list):
            nxt = lines_list[i + 1].strip()
            if nxt and not re.match(r"^[\d\*\-]", nxt) and not nxt.lower().startswith("comments"):
                name = f"{name} {nxt}"
        return _clean_str(name)
    return None


def _find_description_header_product_name(text):
    """Lowest-confidence fallback: a "Description" (or "Product
    Description") table-header line is sometimes followed immediately by
    MORE column headers ("QTY", "UNIT PRICE", "TOTAL PRICE", ...) before
    the actual first product line — a header row with several columns,
    drawn as separate lines. Skip over a bounded run of those before
    trusting a line as real content, rather than blindly grabbing the
    very next line (which used to return "QTY" as a "product name")."""
    header_match = re.search(r"(?im)^\s*(?:product\s+)?description\b\s*$", text)
    if not header_match:
        return None
    remaining = text[header_match.end():].split("\n")
    skipped = 0
    for line in remaining:
        candidate = line.strip()
        if not candidate:
            continue
        if candidate.lower() in _TABLE_HEADER_WORDS:
            skipped += 1
            if skipped > 6:
                return None
            continue
        if candidate.lower().startswith(_BOILERPLATE_STARTS):
            return None
        # A genuinely long, run-together line (several table cells
        # concatenated with no separators — seen when a description
        # cell's text merges with adjacent dimension/quantity data) can't
        # be trusted as a clean product name; honest null beats a
        # garbled 150-character guess.
        if 3 <= len(candidate) <= 120:
            return _clean_str(candidate)
        return None
    return None


_MODEL_NUMBER_LABEL_RE = re.compile(
    r"(?:(?i:item\s*no\.?|model(?:\s*(?:no|number))?|sku))\s*[:.]?\s*([A-Z0-9][A-Z0-9\-]{2,20})"
)
# A table's own column-header row (e.g. "ITEM SKU QTTY GST ...") can have
# its header words glued together with no space by text-run extraction, so
# a label match can accidentally capture the *next* header word instead of
# a real value — reject known header/summary-row words outright rather
# than trust them as a code.
_MODEL_NUMBER_EXCLUDED = {
    "QTY", "QTTY", "GST", "TOTAL", "PRICE", "ITEM", "TAX", "UNIT", "AMOUNT",
    "DESCRIPTION", "DISCOUNT", "SUBTOTAL", "DATE", "NOTES", "TERMS", "SKU",
}
def _find_model_number(text, warnings):
    # NOTE: (?i:...) scopes case-insensitivity to just the label — the
    # whole-pattern (?i) form previously also made the CAPTURED code's
    # [A-Z0-9] class match lowercase, so a header row's next column
    # ("Description", "Quantity", ...) glued onto "Item No." with no space
    # (the same text-run-concatenation issue as the date bug above) would
    # get captured as a bogus "model number".
    #
    # Deliberately no generic "hyphenated all-caps code" fallback beyond
    # this labeled search: an earlier attempt at one (matching any
    # 3+-segment hyphenated token, trusted only when unambiguous) still
    # picked up unrelated hyphenated text with no product connection at
    # all — a freight-surcharge line's internal code and a payment
    # method's "EFTPOS-VISA-MC" label — as if they were the product's
    # model number. A labeled match is a much stronger, safer signal than
    # "looks like a code", so null (with a warning) is the honest answer
    # when no explicit Item No./Model/SKU label is present.
    for m in _MODEL_NUMBER_LABEL_RE.finditer(text):
        candidate = m.group(1)
        if candidate.upper() not in _MODEL_NUMBER_EXCLUDED:
            return candidate

    warnings.append("model_number: no 'Item No./Model/SKU' label found in the document.")
    return None


# A loosely-matched "amount-shaped" token — digits with an integer part of
# any length, then a mandatory decimal separator, then a 2-digit decimal
# part — tolerant of OCR noise that a clean PDF text layer never produces:
# 'O'/'o'/'I'/'l' typed for '0'/'0'/'1'/'1' (classic OCR digit lookalikes),
# a comma used as the decimal separator instead of a period (both appear
# on real receipts depending on locale/printer), and stray whitespace an
# OCR pass sometimes inserts around the separator itself (e.g. photographed
# receipt text read as "8205 , O0" for what a human reads as "$82.05" —
# EasyOCR's known glued-currency-symbol misread). All of that noise is
# resolved by _normalize_amount_token() below; this regex only needs to
# recognize the *shape*.
_AMOUNT_TOKEN = r"[\dOolI][\dOolI,\s]*[.,]\s*[\dOolI]{2}"

_OCR_DIGIT_FIX = str.maketrans({"O": "0", "o": "0", "I": "1", "l": "1"})


def _normalize_amount_token(raw: str):
    """Turn a loosely-matched _AMOUNT_TOKEN capture into a float, or None
    if it doesn't resolve to a plausible amount. Only ever called on text
    a regex has already confirmed is digit/separator/whitespace-shaped
    ending in a 2-digit decimal part, so blanket 'O'/'l' -> '0'/'1'
    substitution can't misfire on ordinary words — it's scoped to numbers
    already recognized as amount-shaped, not applied to text generally.
    The LAST '.' or ',' in the token is taken as the decimal separator
    (whichever punctuation mark that is); every earlier '.'/',' is treated
    as thousands-grouping noise and dropped, rather than trusted to
    reconstruct the original grouping — the exact grouping doesn't matter
    once the decimal point's position is known."""
    token = raw.translate(_OCR_DIGIT_FIX)
    token = re.sub(r"\s+", "", token)
    sep_pos = max(token.rfind("."), token.rfind(","))
    if sep_pos == -1:
        return None
    integer_part = re.sub(r"[.,]", "", token[:sep_pos])
    decimal_part = token[sep_pos + 1 :]
    if not integer_part.isdigit() or len(decimal_part) != 2 or not decimal_part.isdigit():
        return None
    try:
        return float(f"{integer_part}.{decimal_part}")
    except ValueError:
        return None


# Matches a "total" (but not "subtotal"/"sub total") label followed, on the
# SAME line, by a $ amount — this catches the common case where a label
# and its value are drawn as one text run (e.g. "TOTAL PRICE   $  1937.00",
# "Total incl. GST $ 1,649.00"). Deliberately does NOT search across lines:
# PDF content-stream draw order frequently doesn't match visual reading
# order, so hunting further afield risks grabbing an unrelated number (see
# the max-amount fallback's docstring below for the concrete case this
# protects against).
_SAME_LINE_TOTAL_RE = re.compile(
    rf"(?<!sub)(?<!sub )\btotal\b[^\n$]{{0,20}}\$\s*({_AMOUNT_TOKEN})", re.IGNORECASE
)

# Second strategy, for invoices where the label and its value are drawn as
# two SEPARATE lines (own text runs) rather than one combined run — e.g.
# Ozmobiles' summary box:
#   TOTAL :
#   $ 772.50
# Deliberately narrow to avoid the failure mode that motivated the
# same-line-only rule above: only fires when the label line is JUST
# "total" (optionally with a colon) with nothing else on it, AND the
# very next non-blank line (skipping at most one lone "-" sign, for a
# discount row's minus sign on its own line) is ITSELF nothing but a $
# amount. A label like "Invoice Total" does NOT match "total-only", so a
# case where "Invoice Total" is immediately followed by an unrelated
# "Sub-Total" label (as in a Daisy Pool Covers-style invoice, where the
# real total actually appears earlier in the text, not after either
# label) safely falls through to the fallback below unchanged.
_LABEL_ONLY_TOTAL_RE = re.compile(r"^\s*total\s*:?\s*$", re.IGNORECASE)
_LABEL_ONLY_SUBTOTAL_RE = re.compile(r"^\s*sub\s*[- ]?\s*total\b", re.IGNORECASE)
_PURE_AMOUNT_LINE_RE = re.compile(rf"^\s*-?\s*\$\s*({_AMOUNT_TOKEN})\s*$")
_SOLITARY_MINUS_RE = re.compile(r"^\s*-\s*$")


def _find_next_line_total(text):
    lines = text.split("\n")
    found = None
    for i, line in enumerate(lines):
        if _LABEL_ONLY_SUBTOTAL_RE.match(line) or not _LABEL_ONLY_TOTAL_RE.match(line):
            continue
        j = i + 1
        if j < len(lines) and _SOLITARY_MINUS_RE.match(lines[j]):
            j += 1
        if j < len(lines):
            m = _PURE_AMOUNT_LINE_RE.match(lines[j])
            if m:
                amount = _normalize_amount_token(m.group(1))
                if amount is not None:
                    found = amount
    # Last match wins: a discount/tax breakdown's own "total"-ish rows (if
    # any) appear before the final grand total in reading order.
    return found


def _find_purchase_amount(text, warnings):
    same_line = _SAME_LINE_TOTAL_RE.findall(text)
    if same_line:
        amount = _normalize_amount_token(same_line[-1])
        if amount is not None:
            warnings.append(
                f"purchase_amount: taken from the amount immediately following "
                f"a 'total' label on the same line ({amount})."
            )
            return amount

    next_line_total = _find_next_line_total(text)
    if next_line_total is not None:
        warnings.append(
            f"purchase_amount: taken from the amount on the line immediately "
            f"following a standalone 'total' label ({next_line_total})."
        )
        return next_line_total

    # Fallback: collect every $-prefixed amount and take the largest. This
    # is a heuristic, not a real total lookup — it can be wrong when a
    # discount makes the final total *smaller* than the subtotal it's
    # discounted from. It's kept as the fallback because it's empirically
    # correct on several other real invoice layouts where the true total
    # legitimately is the largest number printed, and no explicit total
    # label was found paired with its value.
    amounts = []
    for m in re.finditer(rf"\$\s*({_AMOUNT_TOKEN})", text):
        amount = _normalize_amount_token(m.group(1))
        if amount is not None:
            amounts.append(amount)
    if not amounts:
        warnings.append("purchase_amount: no $-prefixed amount found in the document.")
        return None
    best = max(amounts)
    warnings.append(
        f"purchase_amount: taken as the largest $ amount printed on the "
        f"document ({best}) as a proxy for the grand total — verify against "
        f"the actual invoice total."
    )
    return best


def _find_currency(text):
    # Plain substring checks, deliberately not \b-bounded: acronyms like
    # "ABN" or "AUD" can end up glued directly onto adjacent digits with no
    # separating space after text-run extraction (e.g. "...5000ABN 46..."),
    # which \bABN\b would silently fail to match at all.
    if "AUD" in text or "A$" in text or "AU$" in text:
        return "AUD"
    if "ABN" in text:
        # Australian Business Number — printed on every Australian tax
        # invoice; a strong signal even when "AUD"/"A$" aren't spelled out.
        return "AUD"
    if "GBP" in text or "£" in text:
        return "GBP"
    if "EUR" in text or "€" in text:
        return "EUR"
    if "INR" in text or "₹" in text:
        return "INR"
    if "$" in text:
        return "USD"
    return None


def _find_category(text):
    lower = text.lower()
    for category, keywords in CATEGORY_KEYWORDS:
        if any(kw in lower for kw in keywords):
            return category
    return None


def add_years(d: datetime.date, years: int) -> datetime.date:
    try:
        return d.replace(year=d.year + years)
    except ValueError:
        return d.replace(month=2, day=28, year=d.year + years)


def _build_notes(product_name, brand, purchase_date, category, warranty_mentioned):
    """A short, human-readable description of the purchase — combines what
    was found into one or two plain sentences, rather than exposing raw
    warning fragments to the caller. purchase_amount is deliberately NOT
    included here — it's its own response field (see RESPONSE_FIELDS)."""
    if product_name and brand and brand.lower() not in product_name.lower():
        sentence = f"{brand} {product_name}"
    elif product_name:
        sentence = product_name
    elif brand:
        article = "An" if brand[0].upper() in "AEIOU" else "A"
        sentence = f"{article} {brand} product"
    elif category:
        article = "An" if category[0].upper() in "AEIOU" else "A"
        sentence = f"{article} {category.lower()} item"
    else:
        sentence = "This item"

    parts = [sentence]
    if purchase_date:
        parts.append(f"purchased on {purchase_date}.")
    else:
        parts[-1] = parts[-1].rstrip(".") + "."

    description = " ".join(parts)
    if warranty_mentioned:
        description += " Warranty tracked as 1 year from the purchase date."
    return description.strip()


def extract_fields(text: str) -> dict:
    """Rule-based extraction over already-extracted plain text. Never raises.

    Warranty dates are always computed as purchase_date -> purchase_date +
    1 year whenever a purchase date was found — this is a fixed business
    rule (not conditional on the document mentioning a warranty), matching
    the app's default warranty tracking period."""
    warnings = []

    # Priority order, highest confidence first: an explicit asterisk
    # marker beats an exact code<->prefix match, which beats the looser
    # description-then-code heuristic, which beats the weakest fallback
    # (skip past table headers under a "Description" column). Each is
    # tried only if every higher-priority strategy came up empty.
    product_name = _find_asterisk_product_name(text)
    model_number = None
    if product_name is None:
        product_name, model_number = _find_product_code_pair(text)
    if product_name is None:
        product_name, model_number = _find_description_then_code(text)
    if product_name is None:
        product_name = _find_description_header_product_name(text)
    if product_name is None:
        warnings.append(
            "product_name: no reliable pattern matched (no asterisk-prefixed "
            "line item, no code/description line pair, no usable "
            "'Description' table header found) — needs manual entry."
        )
    if model_number is None:
        model_number = _find_model_number(text, warnings)
    brand = _find_brand(text, warnings)
    purchase_date = _find_purchase_date(text, warnings)
    purchase_amount = _find_purchase_amount(text, warnings)
    currency = _find_currency(text)
    category = _find_category(text)
    warranty_mentioned = bool(re.search(r"warrant|guarantee", text, re.IGNORECASE))

    warranty_start_date = None
    warranty_end_date = None
    if purchase_date is not None:
        start = datetime.date.fromisoformat(purchase_date)
        try:
            warranty_start_date = purchase_date
            warranty_end_date = add_years(start, 1).isoformat()
        except (ValueError, OverflowError):
            # Should be unreachable (purchase_date is already a validated
            # calendar date), but a date-math edge case must never crash
            # the request — fail safe to null rather than a wrong date.
            warnings.append(
                "warranty_end_date: could not compute purchase_date + 1 year; left null."
            )
    else:
        warnings.append(
            "warranty_start_date/warranty_end_date: no purchase_date found to "
            "anchor the 1-year warranty period, so both were left null."
        )

    notes = _build_notes(
        product_name, brand, purchase_date, category, warranty_mentioned
    )

    data = {
        "product_name": product_name,
        "model_number": model_number,
        "other_brand_name": brand,
        "other_category": category,
        "other_categorytype": None,
        "purchase_date": purchase_date,
        "purchase_amount": purchase_amount,
        "currency": currency,
        "warranty_start_date": warranty_start_date,
        "warranty_end_date": warranty_end_date,
        "notes": notes,
        "parts": [],
    }

    core_fields = ["product_name", "purchase_date", "other_brand_name", "purchase_amount"]
    found_count = sum(1 for f in core_fields if data.get(f) is not None)
    weak_signal = any(
        w.startswith(f"{f}:") and ("no " in w or "not matched" in w or "could not" in w)
        for f in core_fields
        for w in warnings
    )
    if found_count == len(core_fields) and not weak_signal:
        confidence = "high"
    elif found_count >= 2:
        confidence = "medium"
    else:
        confidence = "low"
    data["confidence"] = confidence

    fields_not_found = sorted(f for f in core_fields + ["model_number"] if data.get(f) is None)
    data["fields_not_found"] = fields_not_found
    data["warnings"] = warnings

    return data


