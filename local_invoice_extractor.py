"""
Local, offline invoice field extraction — zero third-party packages, zero
AI/cloud API calls. Pure Python standard library only.

Two stages:
  1. `extract_pdf_text()` — a from-scratch PDF text-layer reader (parses
     indirect objects, decompresses FlateDecode content streams, and
     decodes the Tj/TJ text-showing operators). Only handles classic,
     unencrypted PDF structure with simple (1-byte-per-character) text
     encoding, which covers most software-generated invoices — but NOT
     encrypted PDFs, scanned/photographed images, or PDFs using CID/
     Identity-H embedded fonts (no ToUnicode CMap resolution is
     implemented). Raises a clear, specific error in those cases rather
     than silently returning garbage.
  2. `extract_fields()` — regex/keyword rules over that text to find
     product name, dates, amounts, brand, warranty info, etc.

Honesty about accuracy: this is fundamentally weaker than an LLM reading
the document, especially for `product_name` (which has no reliable
generic pattern across invoice layouts). Every field records *why* it
was or wasn't found in `warnings`, and `confidence` reflects how much
was actually pinned down vs. guessed — treat `confidence: "low"` results
as needing manual review.
"""

import datetime
import hashlib
import re
import struct
import zlib

# Presence check for "does this document look like an invoice/receipt at
# all" — used by extract_pdf_text() to refuse documents that clearly
# aren't purchase records (a resume, a government form, ...) before any
# field extraction runs. Real invoices/receipts always carry at least one
# of these: a currency symbol, or one of the standard purchase-document
# words. This is intentionally permissive (a broad OR, not a strict AND)
# — the goal is only to reject documents with NONE of these signals, not
# to second-guess documents that do have them.
_INVOICE_SIGNAL_RE = re.compile(
    r"[$£€₹]"
    r"|\binvoice\b|\breceipt\b|\border\s+confirmation\b|\bpurchase\s+order\b"
    r"|\bsubtotal\b|\bsub[- ]total\b|\bamount\s+due\b|\btotal\s+due\b"
    r"|\bgst\b|\bvat\b|\btotal\b|\btax\s+invoice\b",
    re.IGNORECASE,
)

# --------------------------------------------------------------------------
# Errors
# --------------------------------------------------------------------------


class PdfExtractionError(Exception):
    """Base class — callers should catch this and surface `.message`."""

    code = "pdf_extraction_failed"

    def __init__(self, message, code=None):
        super().__init__(message)
        self.message = message
        if code is not None:
            self.code = code


class EncryptedPdfError(PdfExtractionError):
    """Raised when the file IS encrypted but decryption didn't work out —
    e.g. it actually needs a non-empty password to open."""

    code = "encrypted_pdf"


class UnsupportedEncryptionError(PdfExtractionError):
    """Raised when the file's encryption scheme isn't one this from-scratch
    reader implements (only classic RC4, /V 1 and /V 2, is supported —
    no AES, no public-key security handlers)."""

    code = "unsupported_encryption"


class UnreadablePdfError(PdfExtractionError):
    code = "unreadable_pdf"


class ImageNotSupportedError(PdfExtractionError):
    code = "ocr_not_available"


class NotAnInvoiceError(PdfExtractionError):
    """Raised when the document's text was read successfully but contains
    none of the usual invoice/receipt signals at all — e.g. a passport
    application form or a resume. Text extraction succeeding is not the
    same as the document BEING an invoice; without this check, a random
    date found anywhere in an unrelated document (a date of birth, a form
    submission date) could get confidently reported as "purchase_date"
    with a fabricated warranty period built on top of it. Refusing
    outright is safer than guessing on a document with no purchase
    context at all — and matters more than usual here, since some
    documents that fail this check (a passport form, in the case this
    was written for) carry genuinely sensitive personal data that
    shouldn't be echoed into unrelated fields even accidentally."""

    code = "not_an_invoice"


# --------------------------------------------------------------------------
# Stage 0: classic PDF "Standard" security handler (RC4 only — no AES)
# --------------------------------------------------------------------------
#
# Many invoice/order-confirmation PDFs generated by business software are
# "encrypted" purely to restrict editing/printing — they open with no
# password prompt at all, i.e. an empty *user* password. That's exactly
# what this implements: PDF spec Algorithm 3.2 (compute the file's base
# encryption key) and Algorithm 3.1 (derive each object's own RC4 key from
# it), covering security handler /V 1 and /V 2 (both classic RC4; /R 2/3/4).
# AES (/V 4 crypt filters, /V 5 = AES-256) and non-empty passwords are
# explicitly NOT supported — see UnsupportedEncryptionError / EncryptedPdfError.

_PAD = bytes([
    0x28, 0xBF, 0x4E, 0x5E, 0x4E, 0x75, 0x8A, 0x41,
    0x64, 0x00, 0x4E, 0x56, 0xFF, 0xFA, 0x01, 0x08,
    0x2E, 0x2E, 0x00, 0xB6, 0xD0, 0x68, 0x3E, 0x80,
    0x2F, 0x0C, 0xA9, 0xFE, 0x64, 0x53, 0x69, 0x7A,
])

_ENCRYPT_REF_RE = re.compile(rb"/Encrypt\s+(\d+)\s+0\s+R")
_ID_RE = re.compile(rb"/ID\s*\[\s*<([0-9A-Fa-f]+)>")
_ENC_FILTER_RE = re.compile(rb"/Filter\s*/(\w+)")
_ENC_V_RE = re.compile(rb"/V\s+(\d+)")
_ENC_R_RE = re.compile(rb"/R\s+(\d+)")
_ENC_LENGTH_RE = re.compile(rb"/Length\s+(\d+)")
_ENC_P_RE = re.compile(rb"/P\s+(-?\d+)")
_ENC_O_RE = re.compile(rb"/O\s*\(((?:\\.|[^\\()])*)\)")
_LITERAL_ESCAPE_SIMPLE = {
    0x6E: 0x0A, 0x72: 0x0D, 0x74: 0x09, 0x62: 0x08, 0x66: 0x0C,
    0x28: 0x28, 0x29: 0x29, 0x5C: 0x5C,
}


def _decode_literal_bytes(raw: bytes) -> bytes:
    """Resolve PDF literal-string escapes, returning raw bytes (not text) —
    used for binary strings like /O and /U, not just display text."""
    out = bytearray()
    i, n = 0, len(raw)
    while i < n:
        c = raw[i]
        if c == 0x5C and i + 1 < n:  # backslash
            nxt = raw[i + 1]
            if nxt in _LITERAL_ESCAPE_SIMPLE:
                out.append(_LITERAL_ESCAPE_SIMPLE[nxt])
                i += 2
                continue
            if 0x30 <= nxt <= 0x39:  # octal escape, up to 3 digits
                j = i + 1
                digits = b""
                while j < n and len(digits) < 3 and 0x30 <= raw[j] <= 0x39:
                    digits += bytes([raw[j]])
                    j += 1
                try:
                    out.append(int(digits, 8) & 0xFF)
                except ValueError:
                    pass
                i = j
                continue
            if nxt in (0x0D, 0x0A):  # escaped line break — not part of the string
                i += 2
                if nxt == 0x0D and i < n and raw[i] == 0x0A:
                    i += 1
                continue
            out.append(nxt)
            i += 2
            continue
        out.append(c)
        i += 1
    return bytes(out)


def _rc4(key: bytes, data: bytes) -> bytes:
    key_len = len(key)
    S = list(range(256))
    j = 0
    for i in range(256):
        j = (j + S[i] + key[i % key_len]) & 0xFF
        S[i], S[j] = S[j], S[i]
    out = bytearray(len(data))
    i = j = 0
    for idx in range(len(data)):
        i = (i + 1) & 0xFF
        j = (j + S[i]) & 0xFF
        S[i], S[j] = S[j], S[i]
        out[idx] = data[idx] ^ S[(S[i] + S[j]) & 0xFF]
    return bytes(out)


def _get_encryption_key(raw: bytes, objects: dict):
    """Return the file's base RC4 key assuming an empty user password, or
    None if the document isn't encrypted at all. Raises
    UnsupportedEncryptionError for AES/non-RC4 handlers."""
    encrypt_ref = _ENCRYPT_REF_RE.search(raw)
    if not encrypt_ref:
        return None
    enc_num = int(encrypt_ref.group(1))
    entry = objects.get(enc_num)
    if entry is None:
        raise UnreadablePdfError("Could not locate the PDF's /Encrypt dictionary.")
    _gen, enc_body = entry

    filt = _ENC_FILTER_RE.search(enc_body)
    if filt and filt.group(1) != b"Standard":
        raise UnsupportedEncryptionError(
            f"This PDF uses a non-standard security handler "
            f"('{filt.group(1).decode(errors='replace')}') this offline "
            "extractor doesn't support."
        )

    v_match = _ENC_V_RE.search(enc_body)
    v = int(v_match.group(1)) if v_match else 0
    if v not in (1, 2):
        raise UnsupportedEncryptionError(
            f"This PDF uses encryption algorithm /V {v} (AES or a public-key "
            "handler) — this offline extractor only implements classic RC4 "
            "encryption (/V 1 and /V 2)."
        )

    r_match = _ENC_R_RE.search(enc_body)
    r = int(r_match.group(1)) if r_match else 2

    length_match = _ENC_LENGTH_RE.search(enc_body)
    key_len = (int(length_match.group(1)) // 8) if length_match else 5

    p_match = _ENC_P_RE.search(enc_body)
    p_value = int(p_match.group(1)) if p_match else -1

    o_match = _ENC_O_RE.search(enc_body)
    if not o_match:
        raise UnreadablePdfError("Could not parse the /O value from the /Encrypt dictionary.")
    o_value = _decode_literal_bytes(o_match.group(1))

    id_match = _ID_RE.search(raw)
    doc_id = bytes.fromhex(id_match.group(1).decode()) if id_match else b""

    # Algorithm 3.2: pad the (assumed empty) user password, hash it together
    # with /O, /P, and the first /ID element.
    md5 = hashlib.md5()
    md5.update(_PAD)
    md5.update(o_value)
    md5.update(struct.pack("<i", p_value))
    md5.update(doc_id)
    key = md5.digest()

    if r >= 3:
        for _ in range(50):
            key = hashlib.md5(key[:key_len]).digest()

    return key[:key_len]


def _object_rc4_key(base_key: bytes, obj_num: int, gen_num: int) -> bytes:
    """Algorithm 3.1: each object is RC4-encrypted with its own key derived
    from the file key plus its object/generation numbers."""
    md5 = hashlib.md5()
    md5.update(base_key)
    md5.update(struct.pack("<I", obj_num)[:3])
    md5.update(struct.pack("<I", gen_num)[:2])
    digest = md5.digest()
    return digest[: min(len(base_key) + 5, 16)]


# --------------------------------------------------------------------------
# Stage 1: PDF structure parsing
# --------------------------------------------------------------------------

_OBJ_RE = re.compile(rb"(\d+)\s+(\d+)\s+obj(.*?)endobj", re.DOTALL)
_LENGTH_RE = re.compile(rb"/Length\s+(\d+)")
_FILTER_RE = re.compile(rb"/Filter\s*\[?\s*/?(\w+)")
_TYPE_PAGE_RE = re.compile(rb"/Type\s*/Page(?![A-Za-z])")
_CONTENTS_SINGLE_RE = re.compile(rb"/Contents\s+(\d+)\s+0\s+R")
_CONTENTS_ARRAY_RE = re.compile(rb"/Contents\s*\[([^\]]*)\]")
_REF_RE = re.compile(rb"(\d+)\s+0\s+R")


def _parse_objects(raw: bytes) -> dict:
    """Map object number -> (generation number, raw object body bytes)."""
    objects = {}
    for num, gen, body in _OBJ_RE.findall(raw):
        objects[int(num)] = (int(gen), body)
    return objects


def _get_stream_bytes(body: bytes, decrypt_key=None, obj_num=None, gen_num=0):
    """Extract and decompress a single object's stream, if it has one.
    If the document is encrypted, `decrypt_key` + the object's own
    number/generation are required to RC4-decrypt the raw bytes *before*
    decompression (encryption wraps the already-filtered stream)."""
    dict_part, sep, rest = body.partition(b"stream")
    if not sep:
        return None
    if rest[:2] == b"\r\n":
        rest = rest[2:]
    elif rest[:1] in (b"\n", b"\r"):
        rest = rest[1:]

    length_match = _LENGTH_RE.search(dict_part)
    if length_match:
        raw_stream = rest[: int(length_match.group(1))]
    else:
        raw_stream = rest.split(b"endstream")[0]

    if decrypt_key is not None and obj_num is not None:
        obj_key = _object_rc4_key(decrypt_key, obj_num, gen_num)
        raw_stream = _rc4(obj_key, raw_stream)

    filter_match = _FILTER_RE.search(dict_part)
    filt = filter_match.group(1) if filter_match else None

    if filt == b"FlateDecode":
        try:
            return zlib.decompress(raw_stream)
        except zlib.error:
            if decrypt_key is not None:
                # A wrong decryption key produces zlib garbage — no point
                # rescanning for 'endstream', the bytes are already wrong.
                return None
            # Length may have been slightly off (off-by-one CR/LF quirks) —
            # fall back to scanning for the literal 'endstream' marker.
            try:
                return zlib.decompress(rest.split(b"endstream")[0])
            except zlib.error:
                return None
    if filt in (None, b"ASCIIHexDecode", b"ASCII85Decode"):
        # Uncompressed or a filter we don't implement — return as-is; the
        # text-run scan below will simply find nothing useful in it rather
        # than crashing.
        return raw_stream
    return None


# --------------------------------------------------------------------------
# Stage 1a: CID font support (/Encoding /Identity-H + /ToUnicode CMap)
# --------------------------------------------------------------------------
#
# Many modern PDF generators (headless-Chrome/wkhtmltopdf-style invoice
# templates, in particular) embed each webfont as a CID font with
# /Encoding /Identity-H: every glyph is shown as a 2-byte code (a raw
# font-internal glyph index, NOT a character code), and the *only* way to
# recover the actual text is via that font's /ToUnicode CMap, which maps
# each 2-byte code back to real Unicode. Fonts using a plain 1-byte
# encoding (WinAnsi/StandardEncoding — what Dell/JB Hi-Fi/Daisy Pool
# Covers all use) are unaffected by any of this and keep using the
# existing single-byte decode path below.

_FONT_OBJ_RE = re.compile(rb"/Type\s*/Font\b")
_IDENTITY_H_RE = re.compile(rb"/Encoding\s*/Identity-H\b")
_TOUNICODE_REF_RE = re.compile(rb"/ToUnicode\s+(\d+)\s+0\s+R")
_PAGE_FONT_DICT_RE = re.compile(rb"/Font\s*<<(.*?)>>", re.DOTALL)
_FONT_RESOURCE_ENTRY_RE = re.compile(rb"/([A-Za-z0-9+\-_.]+)\s+(\d+)\s+0\s+R")

_BFCHAR_BLOCK_RE = re.compile(rb"beginbfchar(.*?)endbfchar", re.DOTALL)
_BFCHAR_PAIR_RE = re.compile(rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>")
_BFRANGE_BLOCK_RE = re.compile(rb"beginbfrange(.*?)endbfrange", re.DOTALL)
_BFRANGE_ENTRY_RE = re.compile(
    rb"<([0-9A-Fa-f]+)>\s*<([0-9A-Fa-f]+)>\s*(?:<([0-9A-Fa-f]+)>|\[((?:\s*<[0-9A-Fa-f]+>)+)\s*\])",
    re.DOTALL,
)
_BFRANGE_ARRAY_ITEM_RE = re.compile(rb"<([0-9A-Fa-f]+)>")


def _hex_to_unicode(hex_bytes: bytes) -> str:
    """A ToUnicode destination value is hex-encoded UTF-16BE."""
    hex_str = re.sub(rb"\s+", b"", hex_bytes)
    if len(hex_str) % 2:
        hex_str += b"0"
    try:
        raw = bytes.fromhex(hex_str.decode("ascii"))
    except ValueError:
        return ""
    if len(raw) % 2:
        raw += b"\x00"
    try:
        return raw.decode("utf-16-be", errors="replace")
    except UnicodeDecodeError:
        return ""


def _parse_tounicode_cmap(cmap_bytes: bytes) -> dict:
    """Parse a /ToUnicode CMap stream's beginbfchar/beginbfrange blocks into
    {cid: unicode_string}."""
    mapping = {}
    for block in _BFCHAR_BLOCK_RE.findall(cmap_bytes):
        for src, dst in _BFCHAR_PAIR_RE.findall(block):
            mapping[int(src, 16)] = _hex_to_unicode(dst)
    for block in _BFRANGE_BLOCK_RE.findall(cmap_bytes):
        for m in _BFRANGE_ENTRY_RE.finditer(block):
            start_hex, end_hex, dst_hex, dst_array = m.groups()
            start, end = int(start_hex, 16), int(end_hex, 16)
            if end < start or end - start > 65536:
                continue  # malformed range — never trust it into a huge loop
            if dst_array is not None:
                items = _BFRANGE_ARRAY_ITEM_RE.findall(dst_array)
                for i, item_hex in enumerate(items):
                    if start + i > end:
                        break
                    mapping[start + i] = _hex_to_unicode(item_hex)
            elif dst_hex is not None:
                dst_len = len(dst_hex)
                dst_val = int(dst_hex, 16)
                for i, cid in enumerate(range(start, end + 1)):
                    hex_repr = format(dst_val + i, f"0{dst_len}x").encode("ascii")
                    mapping[cid] = _hex_to_unicode(hex_repr)
    return mapping


def _build_font_unicode_maps(objects: dict, decrypt_key=None) -> dict:
    """Return {font_object_number: {cid: unicode_string}} for every
    Identity-H CID font in the document that has a /ToUnicode CMap. Simple
    (non-CID) fonts are deliberately excluded even if they also carry a
    /ToUnicode entry — they stay on the existing 1-byte decode path."""
    result = {}
    for num, (gen, body) in objects.items():
        if not _FONT_OBJ_RE.search(body) or not _IDENTITY_H_RE.search(body):
            continue
        ref = _TOUNICODE_REF_RE.search(body)
        if not ref:
            continue
        cmap_num = int(ref.group(1))
        cmap_entry = objects.get(cmap_num)
        if cmap_entry is None:
            continue
        cmap_gen, cmap_body = cmap_entry
        cmap_bytes = _get_stream_bytes(cmap_body, decrypt_key=decrypt_key, obj_num=cmap_num, gen_num=cmap_gen)
        if cmap_bytes:
            result[num] = _parse_tounicode_cmap(cmap_bytes)
    return result


def _get_page_font_map(page_body: bytes) -> dict:
    """Parse a page's /Resources /Font <</F1 7 0 R .../>> into
    {resource_name_str: font_object_number}."""
    m = _PAGE_FONT_DICT_RE.search(page_body)
    if not m:
        return {}
    return {name.decode("ascii"): int(num) for name, num in _FONT_RESOURCE_ENTRY_RE.findall(m.group(1))}


def _find_page_content_streams(raw: bytes, objects: dict, decrypt_key=None):
    """Return a list of (content_bytes, page_font_map, font_unicode_maps)
    for every /Type /Page object — the extra two are needed downstream to
    correctly decode any Identity-H CID-encoded text on that page."""
    font_unicode_maps = _build_font_unicode_maps(objects, decrypt_key=decrypt_key)
    streams = []
    for num in sorted(objects):
        gen, body = objects[num]
        if not _TYPE_PAGE_RE.search(body):
            continue

        page_font_map = _get_page_font_map(body)

        content_nums = []
        single = _CONTENTS_SINGLE_RE.search(body)
        if single:
            content_nums.append(int(single.group(1)))
        else:
            array = _CONTENTS_ARRAY_RE.search(body)
            if array:
                content_nums.extend(int(n) for n in _REF_RE.findall(array.group(1)))

        for cnum in content_nums:
            entry = objects.get(cnum)
            if entry is None:
                continue
            cgen, cbody = entry
            data = _get_stream_bytes(cbody, decrypt_key=decrypt_key, obj_num=cnum, gen_num=cgen)
            if data:
                streams.append((data, page_font_map, font_unicode_maps))
    return streams


# --------------------------------------------------------------------------
# Stage 1b: content-stream text-showing operator decoding
# --------------------------------------------------------------------------

_BT_ET_RE = re.compile(rb"BT(.*?)ET", re.DOTALL)
# Adds a font-switch alternative (Tf) ahead of the text-showing operators
# so _decode_content_stream can track which font is active and choose the
# right hex-decoding strategy (CID/Identity-H vs. plain single-byte).
_TEXT_TOKEN_RE = re.compile(
    rb"/([A-Za-z0-9+\-_.]+)\s+[+-]?[\d.]+\s+Tf"  # font switch: /F13 12 Tf
    rb"|\(((?:\\.|[^\\()])*)\)\s*Tj"  # (literal string) Tj
    rb"|<([0-9A-Fa-f\s]*)>\s*Tj"  # <hex string> Tj
    rb"|\[(.*?)\]\s*TJ",  # [ ...array... ] TJ
    re.DOTALL,
)
_ARRAY_ITEM_RE = re.compile(rb"\(((?:\\.|[^\\()])*)\)|<([0-9A-Fa-f\s]*)>")

def _decode_literal(raw: bytes) -> str:
    """Decode a PDF literal string as display text (built on the same
    byte-level escape resolution used for binary /O and /U strings)."""
    return _decode_literal_bytes(raw).decode("latin-1")


def _decode_hex(raw: bytes) -> str:
    """Plain single-byte-per-character hex decode — used for simple
    (non-CID) fonts, i.e. everything except Identity-H CID fonts."""
    hexstr = re.sub(rb"\s+", b"", raw)
    if len(hexstr) % 2:
        hexstr += b"0"
    try:
        data = bytes.fromhex(hexstr.decode("ascii"))
    except ValueError:
        return ""
    return data.decode("cp1252", errors="replace")


def _decode_hex_for_font(raw: bytes, font_obj, font_unicode_maps: dict) -> str:
    """Hex-string decode that's font-aware: if the currently active font is
    a CID/Identity-H font with a known /ToUnicode map, decode 2 bytes per
    glyph and look each one up in that map. Otherwise fall back to the
    plain single-byte decode (_decode_hex) used by simple fonts."""
    cmap = font_unicode_maps.get(font_obj) if font_obj is not None else None
    if not cmap:
        return _decode_hex(raw)
    hexstr = re.sub(rb"\s+", b"", raw)
    if len(hexstr) % 4:
        hexstr += b"0" * (4 - len(hexstr) % 4)
    out = []
    for i in range(0, len(hexstr), 4):
        try:
            cid = int(hexstr[i : i + 4], 16)
        except ValueError:
            continue
        out.append(cmap.get(cid, ""))
    return "".join(out)


def _decode_content_stream(data: bytes, page_font_map=None, font_unicode_maps=None) -> str:
    page_font_map = page_font_map or {}
    font_unicode_maps = font_unicode_maps or {}
    lines = []
    current_font_obj = None  # persists across BT/ET blocks, like real graphics state
    for block_match in _BT_ET_RE.finditer(data):
        block = block_match.group(1)
        parts = []
        for m in _TEXT_TOKEN_RE.finditer(block):
            font_name, literal, hexed, array = m.group(1), m.group(2), m.group(3), m.group(4)
            if font_name is not None:
                current_font_obj = page_font_map.get(font_name.decode("ascii"))
                continue
            if literal is not None:
                parts.append(_decode_literal(literal))
            elif hexed is not None:
                parts.append(_decode_hex_for_font(hexed, current_font_obj, font_unicode_maps))
            elif array is not None:
                for item in _ARRAY_ITEM_RE.finditer(array):
                    if item.group(1) is not None:
                        parts.append(_decode_literal(item.group(1)))
                    elif item.group(2) is not None:
                        parts.append(_decode_hex_for_font(item.group(2), current_font_obj, font_unicode_maps))
        line = "".join(parts).strip()
        if line:
            lines.append(line)
    return "\n".join(lines)


def extract_pdf_text(file_bytes: bytes) -> str:
    """Return the best-effort plain text layer of a PDF, or raise a
    PdfExtractionError subclass explaining why it couldn't.

    Encrypted PDFs are handled by assuming an empty user password (the
    common case for vendor-generated invoices that are merely edit/print
    restricted, not actually password-locked) and decrypting with classic
    RC4 — see _get_encryption_key(). AES and genuinely password-protected
    PDFs raise a clear, specific error rather than pretending to succeed."""
    objects = _parse_objects(file_bytes)
    if not objects:
        raise UnreadablePdfError(
            "Could not parse any objects from this file — it may not be a "
            "valid PDF, or uses a structure (e.g. compressed cross-reference "
            "streams) this offline extractor doesn't support."
        )

    # UnsupportedEncryptionError propagates as-is (AES / non-Standard
    # handler) — nothing we can do about those without a real crypto lib.
    decrypt_key = _get_encryption_key(file_bytes, objects)

    streams = _find_page_content_streams(file_bytes, objects, decrypt_key=decrypt_key)
    if not streams:
        raise UnreadablePdfError(
            "Could not locate any readable page content in this PDF."
        )

    text = "\n".join(
        _decode_content_stream(s, page_font_map=pfm, font_unicode_maps=fum)
        for s, pfm, fum in streams
    ).strip()
    if len(text) < 10:
        if decrypt_key is not None:
            raise EncryptedPdfError(
                "This PDF is encrypted, and decryption was attempted assuming "
                "an empty user password, but produced no readable text — it "
                "likely needs an actual password to open, which this offline "
                "extractor has no way to be given."
            )
        raise UnreadablePdfError(
            "Extracted almost no text from this PDF — it likely uses an "
            "embedded font encoding (e.g. CID/Identity-H) this offline "
            "extractor can't decode, or is a scanned image with no text "
            "layer at all."
        )

    check_invoice_signals(text)
    return text


def check_invoice_signals(text: str) -> None:
    """Raise NotAnInvoiceError if `text` carries none of the usual
    invoice/receipt markers. Public so both the PDF path (above) and the
    OCR path (image_ocr.py, for photographed receipts) apply the exact
    same "does this even look like a purchase document" gate before any
    field extraction runs."""
    if not _INVOICE_SIGNAL_RE.search(text):
        raise NotAnInvoiceError(
            "This document doesn't contain any of the usual invoice/receipt "
            "signals — no currency amount, and none of 'invoice', 'receipt', "
            "'total', 'GST'/'VAT', etc. It doesn't look like a purchase "
            "document, so nothing was extracted from it rather than risk "
            "returning a field (e.g. 'purchase_date') pulled from unrelated "
            "content on the page."
        )


