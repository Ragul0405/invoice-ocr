RESPONSE_FIELDS = (
    "product_name",
    "model_number",
    "other_brand_name",
    "purchase_date",
    "purchase_amount",
    "warranty_start_date",
    "warranty_end_date",
    "notes",
)


def build_success_response(fields: dict) -> dict:
    """Flat response shape: {status: 1, <the 8 requested fields>}. Extra
    diagnostic data (confidence/warnings/etc.) from extract_fields() is
    intentionally NOT included here — this is the exact, minimal field set
    requested for the API contract."""
    response = {"status": 1}
    for key in RESPONSE_FIELDS:
        response[key] = fields.get(key)
    return response


def build_error_response(message: str) -> dict:
    """Flat error shape: {status: 0, message: "..."}."""
    return {"status": 0, "message": message}
